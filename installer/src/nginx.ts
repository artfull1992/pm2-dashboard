import { domainName, safeAbsolutePath } from './validate.js';

// Nginx site for Node Control: static UI from the active release + /api/ to the loopback API (headers per ADR-014).
// Only RENDERED to stdout: placing it, `nginx -t` and reload are explicit operator steps; certificates are obtained by
// the operator (e.g. certbot) — nothing here touches /etc/nginx or other sites.

export interface NginxOptions { serverName: string; certificate: string; certificateKey: string; apiPort?: number }

export function renderNginxSite(o: NginxOptions): string {
  const name = domainName(o.serverName, '--server-name');
  const cert = safeAbsolutePath(o.certificate, '--certificate');
  const key = safeAbsolutePath(o.certificateKey, '--certificate-key');
  const port = o.apiPort ?? 3100;
  return `# Node Control — ${name}. Generated by: node server.js nginx-config (review before use).
# Install: save as /etc/nginx/sites-available/${name}.conf, link into sites-enabled, then nginx -t && systemctl reload nginx.
# Static files: /opt/node-control/current/frontend/dist (root:root, world-readable) — the nginx user only reads them.

server {
    listen 80;
    listen [::]:80;
    server_name ${name};
    return 301 https://$host$request_uri;
}

server {
    listen 443 ssl;
    listen [::]:443 ssl;
    server_name ${name};

    ssl_certificate     ${cert};
    ssl_certificate_key ${key};

    root  /opt/node-control/current/frontend/dist;
    index index.html;

    # API on loopback only. X-Forwarded-For REPLACES the client header (never $proxy_add_x_forwarded_for):
    # the API trusts it only with API_TRUSTED_PROXIES=127.0.0.1 (installer: --behind-nginx).
    location /api/ {
        proxy_pass http://127.0.0.1:${String(port)};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-Host $host;
        proxy_read_timeout 60s;
    }

    location = /index.html {
        add_header Cache-Control "no-store" always;
    }

    location / {
        try_files $uri $uri/ /index.html;
    }
}
`;
}
